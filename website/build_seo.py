"""Generate static English HTML and SEO files: python website/build_seo.py.

Russian index.html and translations.en.json are the content sources.
"""
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
BASE = 'https://mkulkov.github.io/brizfi-downloads/'
TITLES = {
    'ru': 'BRIZFI — передача книг на Kindle с Android и Windows',
    'en': 'BRIZFI — transfer books to Kindle from Android and Windows',
}
DESCRIPTIONS = {
    'ru': 'Передавайте книги на Kindle по Wi-Fi или USB с Android и Windows. BRIZFI подготавливает EPUB и FB2 в AZW3 локально, без регистрации и загрузки книг в облако.',
    'en': 'Transfer books to Kindle over Wi-Fi or USB from Android and Windows. BRIZFI converts EPUB and FB2 to AZW3 locally, without sign-up or uploading books to the cloud.',
}


def metadata(language):
    url = BASE + ('en/' if language == 'en' else '')
    graph = {
        '@context': 'https://schema.org',
        '@graph': [
            {'@type': 'WebSite', '@id': BASE + '#website', 'url': BASE,
             'name': 'BRIZFI', 'inLanguage': ['ru', 'en']},
            {'@type': 'WebPage', '@id': url + '#webpage', 'url': url,
             'name': TITLES[language], 'description': DESCRIPTIONS[language],
             'inLanguage': language, 'isPartOf': {'@id': BASE + '#website'},
             'about': {'@id': BASE + '#application'}},
            {'@type': 'SoftwareApplication', '@id': BASE + '#application',
             'name': 'BRIZFI', 'url': BASE, 'applicationCategory': 'UtilitiesApplication',
             'operatingSystem': 'Android, Windows',
             'description': DESCRIPTIONS[language],
             'image': BASE + 'assets/app-icon-v3.png',
             'license': 'https://www.gnu.org/licenses/gpl-3.0.html',
             'downloadUrl': 'https://github.com/mkulkov/brizfi-downloads/releases'}
        ]
    }
    return '\n'.join([
        '  <!-- SEO: generated by build_seo.py -->',
        f'  <title>{TITLES[language]}</title>',
        f'  <meta name="description" content="{DESCRIPTIONS[language]}">',
        '  <meta name="robots" content="index, follow, max-image-preview:large">',
        f'  <link rel="canonical" href="{url}">',
        f'  <link rel="alternate" hreflang="ru" href="{BASE}">',
        f'  <link rel="alternate" hreflang="en" href="{BASE}en/">',
        f'  <link rel="alternate" hreflang="x-default" href="{BASE}">',
        f'  <link rel="sitemap" type="application/xml" href="{BASE}sitemap.xml">',
        '  <meta property="og:type" content="website">',
        '  <meta property="og:site_name" content="BRIZFI">',
        f'  <meta property="og:locale" content="{"en_US" if language == "en" else "ru_RU"}">',
        f'  <meta property="og:locale:alternate" content="{"ru_RU" if language == "en" else "en_US"}">',
        f'  <meta property="og:url" content="{url}">',
        f'  <meta property="og:title" content="{TITLES[language]}">',
        f'  <meta property="og:description" content="{DESCRIPTIONS[language]}">',
        f'  <meta property="og:image" content="{BASE}assets/app-icon-v3.png">',
        '  <meta property="og:image:alt" content="BRIZFI">',
        '  <meta name="twitter:card" content="summary">',
        f'  <meta name="twitter:title" content="{TITLES[language]}">',
        f'  <meta name="twitter:description" content="{DESCRIPTIONS[language]}">',
        f'  <meta name="twitter:image" content="{BASE}assets/app-icon-v3.png">',
        '  <script type="application/ld+json">',
        json.dumps(graph, ensure_ascii=False, indent=2),
        '  </script>',
        '  <!-- /SEO -->',
    ])


source = (ROOT / 'index.html').read_text(encoding='utf-8')
source = re.sub(r'  <!-- SEO:.*?<!-- /SEO -->\n?', '', source, flags=re.S)
source = re.sub(r'  <title>.*?</title>\n|  <meta (?:name="(?:description|twitter:[^"]+|robots)"|property="og:[^"]+")[^>]*>\n|  <link rel="(?:canonical|alternate|sitemap)"[^>]*>\n', '', source)
source = source.replace('</head>', metadata('ru') + '\n</head>')
(ROOT / 'index.html').write_text(source, encoding='utf-8', newline='\n')
translations = json.loads((ROOT / 'translations.en.json').read_text(encoding='utf-8'))
english = source.replace('<html lang="ru">', '<html lang="en">')
pattern = r'<(?P<tag>[a-z][a-z0-9]*)\b(?P<attrs>[^>]*\bdata-i18n="(?P<key>[^"]+)"[^>]*)>.*?</(?P=tag)>'
english = re.sub(pattern, lambda m: f'<{m["tag"]}{m["attrs"]}>{translations[m["key"]]}</{m["tag"]}>', english, flags=re.S)
for attribute in ('alt', 'aria-label'):
    def translate_attribute(match):
        tag = match[0]
        key = re.search(fr'data-i18n-{attribute}="([^"]+)"', tag)[1]
        return re.sub(fr'(?<![\w-]){attribute}="[^"]*"', f'{attribute}="{html.escape(translations[key], quote=True)}"', tag)
    english = re.sub(fr'<[^>]+data-i18n-{attribute}="[^"]+"[^>]*>', translate_attribute, english)
english = re.sub(r'  <!-- SEO:.*?<!-- /SEO -->', lambda _: metadata('en'), english, flags=re.S)
english = english.replace('href="assets/', 'href="../assets/').replace('src="assets/', 'src="../assets/').replace('href="styles.css', 'href="../styles.css').replace('src="languages.js', 'src="../languages.js')
english = english.replace('<option value="en" lang="en">', '<option value="en" lang="en" selected>')
english = english.replace('href="./" hreflang="ru"', 'href="../" hreflang="ru"').replace('href="en/" hreflang="en"', 'href="./" hreflang="en"')
(ROOT / 'en').mkdir(exist_ok=True)
(ROOT / 'en/index.html').write_text(english, encoding='utf-8', newline='\n')
(ROOT / 'sitemap.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + ''.join(f'  <url><loc>{BASE}{path}</loc></url>\n' for path in ('', 'en/')) + '</urlset>\n', encoding='utf-8', newline='\n')
