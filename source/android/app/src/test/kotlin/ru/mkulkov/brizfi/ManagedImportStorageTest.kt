package ru.mkulkov.brizfi

import java.io.ByteArrayInputStream
import java.io.File
import java.nio.file.Files
import java.util.UUID
import java.util.concurrent.CountDownLatch
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit
import org.junit.After
import org.junit.Assert.*
import org.junit.Assume.assumeNoException
import org.junit.Test

class ManagedImportStorageTest {
    private val parent = Files.createTempDirectory("brizfi-storage-test").toFile().canonicalFile
    private val root = File(parent, "brizfi_imports")
    private var time = 100_000L
    private fun storage(quota: Long = 350) = ManagedImportStorage(root, { time }, 100, quota, 1_000)
    private fun copy(store: ManagedImportStorage = storage(), bytes: Int = 50): File =
        store.importBook("book.epub", { ByteArrayInputStream(ByteArray(bytes) { 7 }) }, { false })
    private fun fails(code: String, action: () -> Unit) {
        try {
            action()
            fail("Expected $code")
        } catch (error: ManagedImportStorage.Failure) {
            assertEquals(code, error.code)
        }
    }
    private fun oldOwned(age: Long, name: String = UUID.randomUUID().toString()): File =
        File(root, name).apply {
            mkdirs()
            File(this, ".brizfi_owned").apply {
                writeText("brizfi-import-v1\n$name\n")
                setLastModified(time - age)
            }
            File(this, "book.epub").writeBytes(ByteArray(10))
        }

    @After fun tearDown() { parent.deleteRecursively() }

    @Test fun perFileLimitRollsBackOnlyNewCopy() {
        val original = File(parent, "original.epub").apply { writeBytes(ByteArray(101)) }
        val input = copy()
        fails("too_large") { storage().importBook("book.epub", { original.inputStream() }, { false }) }
        assertTrue(input.exists())
        assertEquals(101L, original.length())
        assertEquals(1, root.listFiles()!!.size)
    }

    @Test fun quotaIncludesLegacyAndMarkerBytesWithoutEvictingFreshImports() {
        root.mkdirs()
        val legacy = File(root, "legacy").apply { mkdir(); File(this, "old").writeBytes(ByteArray(200)) }
        val first = copy()
        fails("cache_full") { copy(bytes = 1) }
        assertTrue(first.exists())
        assertTrue(legacy.exists())
        assertEquals(2, root.listFiles()!!.size)
    }

    @Test fun reservationIsSharedAndOutputIsNotCountedTwice() {
        val firstStore = storage()
        val input = copy(firstStore)
        val second = copy()
        firstStore.reserveConversion(input.path)
        fails("busy") { storage().reserveConversion(input.path) }
        File("${input.path}.converted.azw3").writeBytes(ByteArray(100))
        // Generated bytes occupy the reservation, rather than being added again.
        storage().finishConversion(input.path)
        assertTrue(second.exists())
        fails("cache_full") { storage().reserveConversion(second.path) }
        storage().releaseImport(input.path)
        storage().reserveConversion(second.path)
        storage().finishConversion(second.path)
    }

    @Test fun activeConversionProtectsReleaseAndCleanupAcrossInstances() {
        val store = storage()
        val input = copy(store)
        store.reserveConversion(input.path)
        time += 2_000
        fails("busy") { storage().releaseImport(input.path) }
        storage().clearExpiredImports()
        assertTrue(input.exists())
        storage().finishConversion(input.path)
        storage().releaseImport(input.path)
        assertFalse(requireNotNull(input.parentFile).exists())
    }

    @Test fun cleanupRemovesOnlyStaleMarkedNonLiveDirectories() {
        val expired = oldOwned(2_000)
        val fresh = oldOwned(500)
        val legacy = File(root, UUID.randomUUID().toString()).apply {
            mkdir(); File(this, "book.epub").writeText("legacy"); setLastModified(0)
        }
        val live = copy(storage(quota = 1_000))
        time += 2_000
        File(fresh, ".brizfi_owned").setLastModified(time)
        storage().clearExpiredImports()
        assertFalse(expired.exists())
        assertTrue(fresh.exists())
        assertTrue(legacy.exists())
        assertTrue(live.exists())
    }

    @Test fun releaseRejectsOriginalUnmarkedNestedAndTraversalPaths() {
        val store = storage()
        val original = File(parent, "original.epub").apply { writeText("original") }
        val unmarked = File(root, UUID.randomUUID().toString()).apply { mkdirs() }
        val file = File(unmarked, "book.epub").apply { writeText("legacy") }
        val input = copy()
        fails("import_failed") { store.releaseImport(original.path) }
        fails("import_failed") { store.reserveConversion(original.path) }
        fails("import_failed") { store.releaseImport(file.path) }
        val inputDirectory = requireNotNull(input.parentFile)
        fails("import_failed") { store.releaseImport(File(inputDirectory, "../${inputDirectory.name}/book.epub").path) }
        assertTrue(original.exists())
        assertTrue(file.exists())
        assertTrue(input.exists())
    }

    @Test fun symlinksCannotAuthorizeReleaseOrQuotaTraversal() {
        val original = File(parent, "outside").apply { mkdir(); File(this, "book.epub").writeText("keep") }
        root.mkdirs()
        val link = File(root, UUID.randomUUID().toString())
        try { Files.createSymbolicLink(link.toPath(), original.toPath()) }
        catch (error: Exception) { assumeNoException(error) }
        fails("import_failed") { storage().releaseImport(File(link, "book.epub").path) }
        fails("storage_unavailable") { copy() }
        assertEquals("keep", File(original, "book.epub").readText())
        // Avoid relying on recursive teardown's platform symlink handling.
        Files.deleteIfExists(link.toPath())
    }

    @Test fun unavailableRootReturnsPathFreeCode() {
        root.writeText("occupied")
        fails("storage_unavailable") { copy() }
        assertEquals("occupied", root.readText())
    }

    @Test fun concurrentInstancesCannotOverbookQuota() {
        val executor = Executors.newFixedThreadPool(2)
        val start = CountDownLatch(1)
        try {
            val results = (1..2).map {
                executor.submit<String> {
                    start.await()
                    try { copy(storage(quota = 180)); "ok" }
                    catch (error: ManagedImportStorage.Failure) { error.code }
                }
            }
            start.countDown()
            assertEquals(listOf("cache_full", "ok"), results.map { it.get(5, TimeUnit.SECONDS) }.sorted())
            assertEquals(1, root.listFiles()!!.size)
        } finally { executor.shutdownNow() }
    }

    @Test fun failedOutputValidationReleasesReservationAndPreservesInput() {
        val store = storage()
        val input = copy(store)
        store.reserveConversion(input.path)
        File("${input.path}.converted.azw3").writeBytes(ByteArray(101))
        fails("cache_full") { store.finishConversion(input.path) }
        assertTrue(input.exists())
        store.releaseImport(input.path)
        assertFalse(requireNotNull(input.parentFile).exists())
    }

    @Test fun allOriginalFormatsAreCopiedAndUnsupportedNamesNeverOpenSource() {
        val store = storage(quota = 2_000)
        listOf("epub", "fb2", "azw3", "mobi", "pdf", "txt").forEach {
            val input = store.importBook("book.$it", { ByteArrayInputStream(byteArrayOf(1, 2)) }, { false })
            assertArrayEquals(byteArrayOf(1, 2), input.readBytes())
        }
        var opened = false
        fails("unsupported_format") {
            store.importBook("book.exe", { opened = true; ByteArrayInputStream(byteArrayOf(1)) }, { false })
        }
        assertFalse(opened)
        assertEquals(6, root.listFiles()!!.size)
    }

    @Test fun alternateOutputsSurviveAndBothCountAgainstNextReservation() {
        val store = storage(quota = 500)
        val input = copy(store)
        val azw3 = File("${input.path}.converted.azw3").apply { writeBytes(ByteArray(80) { 1 }) }
        store.reserveConversion(input.path)
        val epub = File("${input.path}.converted.epub").apply { writeBytes(ByteArray(90) { 2 }) }
        store.finishConversion(input.path)
        assertEquals(80L, azw3.length())
        assertEquals(90L, epub.length())
        // About 278 bytes already exist; a 100-byte new output does not fit 350.
        fails("cache_full") { storage(quota = 350).reserveConversion(input.path) }
        assertEquals(80L, azw3.length())
        assertEquals(90L, epub.length())
        store.releaseImport(input.path)
    }

    @Test fun oversizeEpubOutputReleasesLeaseAndKeepsInputAndOtherVariant() {
        val store = storage(quota = 500)
        val input = copy(store)
        val azw3 = File("${input.path}.converted.azw3").apply { writeBytes(ByteArray(50)) }
        store.reserveConversion(input.path)
        File("${input.path}.converted.epub").writeBytes(ByteArray(101))
        fails("cache_full") { store.finishConversion(input.path) }
        assertTrue(input.exists())
        assertEquals(50L, azw3.length())
        store.releaseImport(input.path)
    }
}
